# 特征探测器：从问题里识别「用于适用性判断」的具体事实
def detect_features(question: str) -> dict:
    f = {}

    # 房东类型：个人房东 vs 长租公寓/转租企业
    if re.search(r"长租公寓|自如|蛋壳|公寓公司|品牌公寓|转租", question):
        f["landlord_type"] = "长租公寓/转租企业"
    elif re.search(r"房东", question):
        f["landlord_type"] = "个人房东"
    # 注意：「中介」不归入「个人房东」——中介既可能是居间（房东是个人），
    # 也可能是转租企业，仅凭「中介」无法判定房东类型，应留空交给 verify 判「无法确定」。

    # 租房 vs 买房
    if re.search(r"买房|购房|首付|房贷|二手房|房价|按揭", question):
        f["housing_type"] = "买房"
    elif re.search(r"租房|房租|租金|押金|房东|租客|租户|租", question):
        f["housing_type"] = "租房"

    # 离职类型
    if re.search(r"被裁|裁员|辞退|解雇|炒鱿鱼|优化", question):
        f["resign_type"] = "被裁/被辞退"
    elif re.search(r"辞职|裸辞|主动走|不干了|跳槽|离职", question):
        f["resign_type"] = "主动辞职"

    # 是否涉及预付
    if re.search(r"一次.{0,4}(交|付|给).{0,8}(年|季|半年)|预付|预交", question):
        f["prepay"] = True

    # 预算金额
    m = re.search(r"(\d+(?:\.\d+)?)\s*(万|千|块|元|k|K)", question)
    if m:
        f["budget"] = m.group(0)

    # 使用年限
    m = re.search(r"开\s*(\d+)\s*年|用\s*(\d+)\s*年", question)
    if m:
        f["duration_years"] = m.group(1) or m.group(2)

    return f


def parse_question(question: str) -> dict:
    """把大白话问题解析成结构化情境。只做规则映射，不生成新知识。

    多组情境模式都会尝试，领域做并集，意图以「更具体的模式（靠后）」为准。
    """
    situation = {
        "question": question,
        "domain": [],
        "object": "",
        "intent": "",
        "risk": "",
        "features": {},
    }
    for pattern, vals in SITUATION_PATTERNS:
        if re.search(pattern, question):
            for k, v in vals.items():
                if k == "domain":
                    situation["domain"] = list(dict.fromkeys(situation["domain"] + v))
                else:
                    situation[k] = v  # object/intent 以更具体（靠后）的模式为准

    # 兜底：用领域别名补全 domain（纯关键词 → 章节映射，不引入新知识）
    for alias, chs in CATEGORY_ALIASES.items():
        if alias in question:
            situation["domain"] = list(dict.fromkeys(situation["domain"] + chs))

    # 风险线索（用户表达的担心）
    for kw in ["担心", "不踏实", "风险", "怕", "亏", "会不会", "划不划算", "值不值"]:
        if kw in question:
            situation["risk"] = kw
            break

    situation["features"] = detect_features(question)
    return situation


